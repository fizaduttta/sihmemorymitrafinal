export function translate(lang: Language, key: string, vars?: Record<string, string>): string {
  let value = dicts[lang]?.[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${k}\\}`, "g"), v)
    }
  }
  return value
}

